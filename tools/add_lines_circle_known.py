def main():
    files = sorted(glob.glob(os.path.join(ROOT, "defaults", "personas", "*.json")))
    assert len(files) == len(LINES) == 27, (len(files), len(LINES))
    assert all(len(v) == len(KEYS) for v in LINES.values())
    n = 0
    for f in files:
        src = io.open(f, encoding="utf-8", newline="").read()
        p = json.loads(src)
        add = [(k, t) for k, t in zip(KEYS, LINES[p["id"]]) if k not in p["lines"]]
        if not add:
            continue
        tail = "\n }\n}"                      # "lines" が最後の塊: 文字として差し込む (ファイルの書式を保つ)
        at = src.rindex(tail)
        assert list(p)[-1] == "lines", f
        ins = "".join(',\n  %s: [\n   %s\n  ]' % (json.dumps(k), json.dumps(t, ensure_ascii=False)) for k, t in add)
        out = src[:at] + ins + src[at:]
        q = json.loads(out)
        assert all(q["lines"][k] == [t] for k, t in add) and len(q["lines"]) == len(p["lines"]) + len(add)
        io.open(f, "w", encoding="utf-8", newline="").write(out)
        n += len(add)
    print("ok", n, "行")


if __name__ == "__main__":
    main()
