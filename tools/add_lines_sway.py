def main():
    n = 0
    for pid, lines in sorted(L.items()):
        assert len(lines) == len(KEYS), (pid, len(lines))
        path = os.path.join(BASE, "defaults", "personas", pid + ".json")
        p = json.load(io.open(path, encoding="utf-8"))
        for i, (k, t) in enumerate(zip(KEYS, lines)):
            p["lines"][k] = ["📱『%s』" % t if i < CHAT else t]
            n += 1
        with io.open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(json.dumps(p, ensure_ascii=False, indent=1) + "\n")
    print("%d 性格・%d 行" % (len(L), n))


if __name__ == "__main__":
    main()
