def main():
    pdir = os.path.join(BASE, "defaults", "personas")
    files = sorted(f for f in os.listdir(pdir) if f.endswith(".json"))
    assert {f[:-5] for f in files} == set(LINES), set(LINES) ^ {f[:-5] for f in files}
    assert all(len(v) == len(KEYS) for v in LINES.values()), [k for k, v in LINES.items() if len(v) != len(KEYS)]
    n = 0
    for f in files:
        path = os.path.join(pdir, f)
        src = io.open(path, encoding="utf-8", newline="").read()
        p = json.loads(src)
        add = [(k, v) for k, v in zip(KEYS, LINES[f[:-5]]) if k not in p["lines"]]
        if not add:
            continue
        tail = "\n }\n}"                      # "lines" は最後の塊: 文字として差し込む (ファイルの書式を保つ)
        at = src.rindex(tail)
        assert list(p)[-1] == "lines", f
        ins = "".join(',\n  %s: [\n   %s\n  ]' % (json.dumps(k), json.dumps(v, ensure_ascii=False)) for k, v in add)
        out = src[:at] + ins + src[at:]
        q = json.loads(out)
        assert all(q["lines"][k] == [v] for k, v in add) and len(q["lines"]) == len(p["lines"]) + len(add)
        io.open(path, "w", encoding="utf-8", newline="").write(out)
        n += len(add)
    print("足した行: %d" % n)


if __name__ == "__main__":
    main()
