def main():
    done = 0
    for f in sorted(os.listdir(D)):
        if not f.endswith(".json"):
            continue
        pid = f[:-5]
        if pid not in LINES:
            raise SystemExit("セリフが無い性格: %s" % pid)
        rows = LINES[pid]
        assert len(rows) == len(KEYS), pid
        p = os.path.join(D, f)
        raw = io.open(p, encoding="utf-8").read()
        d = json.loads(raw)
        L = d.setdefault("lines", {})
        for k, text in zip(KEYS, rows):
            key = "chat.appoint_" + k
            if key not in L:
                L[key] = ["📱『%s』" % text]
                done += 1
        io.open(p, "w", encoding="utf-8", newline="").write(json.dumps(d, ensure_ascii=False, indent=1) + ("\n" if raw.endswith("\n") else ""))
    print("足した行:", done)


if __name__ == "__main__":
    main()
