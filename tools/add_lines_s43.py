def main():
    aps = {a["id"]: a for a in json.load(open(os.path.join(ROOT, "defaults", "approaches.json"), encoding="utf-8"))}
    narr = {}
    for aid in FOND + ("play_again", "movie_invite"):
        a = aps[aid]
        if (a.get("ignore") or {}).get("text"):
            narr["ap.%s.ignore" % aid] = a["ignore"]["text"]
        if (a.get("ignore") or {}).get("busy_text"):
            narr["ap.%s.busy" % aid] = a["ignore"]["busy_text"]
    total = 0
    for pid, lines in L.items():
        assert len(lines) == len(KEYS), (pid, len(lines), len(KEYS))
        p = os.path.join(ROOT, "defaults", "personas", pid + ".json")
        d = json.load(open(p, encoding="utf-8"))
        lk = d["lines"]
        n = 0
        for k, t in list(zip(KEYS, lines)) + list(narr.items()):
            aid = k.split(".")[1]
            if k.endswith(".accept") and aid in ACCEPT_NARR and not t.startswith("（"):
                t = ACCEPT_NARR[aid] + t
            if k not in lk:
                lk[k] = [t]
                n += 1
        if n:
            with open(p, "w", encoding="utf-8", newline="\n") as f:
                f.write(json.dumps(d, ensure_ascii=False, indent=1) + "\n")
        total += n
        print(pid, n)
    print("total", total)


if __name__ == "__main__":
    main()
