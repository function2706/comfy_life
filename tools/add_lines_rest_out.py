def main(apply):
    import glob
    import os
    files = sorted(glob.glob("defaults/personas/*.json"))
    assert sorted(os.path.basename(f)[:-5] for f in files) == sorted(L), set(L) ^ {os.path.basename(f)[:-5] for f in files}
    n = 0
    for f in files:
        pid = os.path.basename(f)[:-5]
        raw = open(f, encoding="utf-8", newline="").read()
        d = json.loads(raw)
        assert len(L[pid]) == len(K), pid
        for k, t in zip(K, L[pid]):
            d["lines"][k] = [t]
            n += 1
        if apply:
            ind = 1 if raw.startswith("{\n \"") else 2
            out = json.dumps(d, ensure_ascii=False, indent=ind) + ("\n" if raw.endswith("\n") else "")
            open(f, "w", encoding="utf-8", newline="").write(out)
    print("lines", n)
    if "--count" in sys.argv:
        allt = "\n".join(t for v in L.values() for t in v)
        for w in ("正直", "贅沢", "さっき休んだ", "実は", "助か", "限界", "気づいて", "楽ちん", "ありがと"):
            print(w, allt.count(w))


if __name__ == "__main__":
    main("--apply" in sys.argv)
